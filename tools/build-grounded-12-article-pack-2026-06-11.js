function body(paragraphs) {
  const rawText = paragraphs.map((line) => line.trim()).filter(Boolean).join("\n\n");
  return smoothParagraphRhythm(rawText);
}

function nonWhitespaceCount(text) {
  return (text.match(/\S/g) || []).length;
}

function splitParagraphs(text) {
  return String(text || "")
    .replace(/\r\n/g, "\n")
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.replace(/\s+/g, " ").trim())
    .filter(Boolean);
}

function paragraphCount(text) {
  return splitParagraphs(text).length;
}

function paragraphStats(text) {
  const paragraphs = splitParagraphs(text);
  const lengths = paragraphs.map((paragraph) => nonWhitespaceCount(paragraph));
  return {
    paragraphs: paragraphs.length,
    shortestParagraph: lengths.length ? Math.min(...lengths) : 0,
    longestParagraph: lengths.length ? Math.max(...lengths) : 0,
    averageParagraph: lengths.length
      ? Math.round(lengths.reduce((sum, value) => sum + value, 0) / lengths.length)
      : 0,
    veryShortParagraphs: lengths.filter((value) => value < 45).length,
  };
}

function shouldMergeParagraph(current, next) {
  if (!next) return false;
  const currentLength = nonWhitespaceCount(current);
  const nextLength = nonWhitespaceCount(next);
  const combinedLength = currentLength + nextLength;
  if (combinedLength > 230) return false;
  if (currentLength < 72) return true;
  const connectorLead = /^(但|可是|如果|若|也要|還要|比較|真正|接著|所以|這時|最後|不要|可以|有些|很多|先|當|等到)/;
  return currentLength < 92 && nextLength < 125 && connectorLead.test(current);
}

function smoothParagraphRhythm(text) {
  const paragraphs = splitParagraphs(text);
  const merged = [];
  for (let index = 0; index < paragraphs.length; index += 1) {
    let paragraph = paragraphs[index];
    while (shouldMergeParagraph(paragraph, paragraphs[index + 1])) {
      paragraph = `${paragraph}${paragraph.endsWith("。") ? "" : "。"}${paragraphs[index + 1]}`;
      index += 1;
    }
    if (nonWhitespaceCount(paragraph) < 45 && merged.length > 0) {
      merged[merged.length - 1] = `${merged[merged.length - 1]}${paragraph}`;
    } else {
      merged.push(paragraph);
    }
  }
  return merged.join("\n\n");
}

