function validateArticles() {
  const ids = new Set();
  const normalizedTitles = new Set();
  const titleArchetypes = new Set();
  const styleStatsList = [];
  for (const article of articles) {
    if (ids.has(article.id)) throw new Error(`duplicate article id: ${article.id}`);
    ids.add(article.id);
    if (!article.titleArchetype) throw new Error(`${article.id} titleArchetype missing`);
    titleArchetypes.add(article.titleArchetype);
    const awkwardTitle = awkwardTitlePatterns.filter((pattern) => pattern.test(article.title));
    if (awkwardTitle.length) throw new Error(`${article.id} awkward title phrasing: ${awkwardTitle.join(", ")}`);
    const normalizedTitle = normalizeTitleForSimilarity(article.title);
    if (normalizedTitles.has(normalizedTitle)) throw new Error(`duplicate normalized title: ${article.title}`);
    normalizedTitles.add(normalizedTitle);
    const chars = nonWhitespaceCount(article.text);
    if (chars <= 2000) throw new Error(`${article.id} body too short: ${chars}`);
    const leaks = bannedBodyPatterns.filter((pattern) => pattern.test(article.text));
    if (leaks.length) throw new Error(`${article.id} role/meta leaks: ${leaks.join(", ")}`);
    const awkward = awkwardBodyPatterns.filter((pattern) => pattern.test(article.text));
    if (awkward.length) throw new Error(`${article.id} awkward phrasing: ${awkward.join(", ")}`);
    const rhythm = paragraphStats(article.text);
    if (rhythm.paragraphs > 24) throw new Error(`${article.id} too many fragmented paragraphs: ${rhythm.paragraphs}`);
    if (rhythm.veryShortParagraphs > 0) {
      throw new Error(`${article.id} has very short paragraphs: ${rhythm.veryShortParagraphs}`);
    }
    if (rhythm.averageParagraph < 100) throw new Error(`${article.id} paragraph average too short: ${rhythm.averageParagraph}`);
    if (rhythm.longestParagraph > 240) throw new Error(`${article.id} paragraph too long: ${rhythm.longestParagraph}`);
    const styleStats = stylePatternStats(article.text);
    if (styleStats.notButCount > 3) throw new Error(`${article.id} overuses not-but pattern: ${styleStats.notButCount}`);
    if (styleStats.stablePhraseCount > 0) throw new Error(`${article.id} contains 比較穩 phrase`);
    if (styleStats.selfQuestionTransitionCount > 1) {
      throw new Error(`${article.id} has too many self-question transitions: ${styleStats.selfQuestionTransitionCount}`);
    }
    if (styleStats.trueNeedCount > 3) throw new Error(`${article.id} overuses 真正: ${styleStats.trueNeedCount}`);
    styleStatsList.push(styleStats);
  }
  const notButTotal = styleStatsList.reduce((sum, item) => sum + item.notButCount, 0);
  const articlesWithNotBut = styleStatsList.filter((item) => item.notButCount > 0).length;
  if (notButTotal > articles.length) {
    throw new Error(`article pack overuses not-but pattern: total=${notButTotal}, articles=${articles.length}`);
  }
  if (articlesWithNotBut > Math.floor(articles.length / 2)) {
    throw new Error(`article pack has too many articles using not-but pattern: ${articlesWithNotBut}/${articles.length}`);
  }
  if (titleArchetypes.size < 6) {
    throw new Error(`article pack title archetypes too narrow: ${titleArchetypes.size}/6`);
  }
}

