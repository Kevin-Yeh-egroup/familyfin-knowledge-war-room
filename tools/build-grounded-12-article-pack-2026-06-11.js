function run() {
  validateArticles();
  ensureDir(packDir);
  const enrichedArticles = articles.map((article, index) => {
    const bodyPath = path.join(packDir, article.fileName);
    fs.writeFileSync(bodyPath, `正文\n${article.text}\n`, "utf8");
    return buildArticleRecord(article, index);
  });
  const counts = enrichedArticles.map((article) => article.bodyChars);
  const whitespaceCounts = enrichedArticles.map((article) => article.bodyCharsIncludingWhitespace);
  const paragraphRhythms = enrichedArticles.map((article) => article.paragraphRhythmGate.stats);
  const paragraphCounts = paragraphRhythms.map((item) => item.paragraphs);
  const averageParagraphs = paragraphRhythms.map((item) => item.averageParagraph);
  const longestParagraphs = paragraphRhythms.map((item) => item.longestParagraph);
  const shortestParagraphs = paragraphRhythms.map((item) => item.shortestParagraph);
  const styleStats = enrichedArticles.map((article) => article.styleVariationGate.stats);
  const stats = {
    articleCount: enrichedArticles.length,
    bodyCharsMin: Math.min(...counts),
    bodyCharsMax: Math.max(...counts),
    bodyCharsIncludingWhitespaceMin: Math.min(...whitespaceCounts),
    bodyCharsIncludingWhitespaceMax: Math.max(...whitespaceCounts),
    paragraphRhythm: {
      paragraphsMin: Math.min(...paragraphCounts),
      paragraphsMax: Math.max(...paragraphCounts),
      averageParagraphMin: Math.min(...averageParagraphs),
      averageParagraphMax: Math.max(...averageParagraphs),
      shortestParagraphMin: Math.min(...shortestParagraphs),
      longestParagraphMax: Math.max(...longestParagraphs),
      veryShortParagraphsTotal: paragraphRhythms.reduce((sum, item) => sum + item.veryShortParagraphs, 0),
    },
    styleVariation: {
      notButMax: Math.max(...styleStats.map((item) => item.notButCount)),
      notButTotal: styleStats.reduce((sum, item) => sum + item.notButCount, 0),
      articlesWithNotBut: styleStats.filter((item) => item.notButCount > 0).length,
      stablePhraseTotal: styleStats.reduce((sum, item) => sum + item.stablePhraseCount, 0),
      selfQuestionMax: Math.max(...styleStats.map((item) => item.selfQuestionTransitionCount)),
      trueNeedMax: Math.max(...styleStats.map((item) => item.trueNeedCount)),
    },
    bodyFiles: enrichedArticles.map((article) => article.bodyPath),
    titles: enrichedArticles.map((article) => article.title),
  };
  updateSuggestions(enrichedArticles, stats);
  updateHistory(stats);
  writeReport(stats);
  const auditBodyCounts = stats.bodyFiles.map((relativePath) => {
    const raw = fs.readFileSync(path.join(repoRoot, relativePath), "utf8");
    const text = bodyText(raw);
    return { path: relativePath, chars: nonWhitespaceCount(text) };
  });
  console.log(
    JSON.stringify(
      {
        status: "ok",
        packId,
        articleCount: stats.articleCount,
        bodyCharsMin: stats.bodyCharsMin,
        bodyCharsMax: stats.bodyCharsMax,
        auditBodyCounts,
      },
      null,
      2,
    ),
  );
}

run();
